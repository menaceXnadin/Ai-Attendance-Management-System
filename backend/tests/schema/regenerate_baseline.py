"""Regenerate ``tests/schema/baseline.sql`` (and optionally ``seed_reference.sql``) from the live DB.

READ-ONLY on the live database: runs ``pg_dump --schema-only`` and (with ``--seed``) plain
SELECTs, both with ``default_transaction_read_only=on``. Nothing is ever written to live.

Usage (from backend/)::

    venv/Scripts/python.exe tests/schema/regenerate_baseline.py [--seed] [--pg-bin "C:/Program Files/PostgreSQL/17/bin"]

After regenerating, update ``BASELINE_REVISION`` in tests/support/testenv.py if the live
DB's alembic head changed.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tests.support.testenv import (  # noqa: E402
    BASELINE_SQL,
    LIVE_DB_NAME,
    SEED_SQL,
    clean_dump_sql,
    server_url,
)

HEADER = """\
-- AttendAI test-harness baseline schema.
-- Generated by tests/schema/regenerate_baseline.py from:
--   pg_dump --schema-only --no-owner --no-privileges -T 'students_backup_*' attendancedb
-- (read-only on live). Post-processing: psql meta-commands and PG17-only SETs removed.
-- Corresponds to alembic revision n20251103_payload_receipts (the harness stamps it, then
-- runs `alembic upgrade head`). Do not edit by hand; regenerate instead.

"""

SEED_QUERY = r"""
SELECT format('INSERT INTO public.system_settings (id, key, value, category, description, data_type, is_active, updated_by, created_at, updated_at) VALUES (%s, %L, %L::jsonb, %L, %L, %L, %L, NULL, %L, %L);',
  id, key, value::text, category, description, data_type, is_active, created_at, updated_at)
FROM public.system_settings ORDER BY id;
SELECT format('INSERT INTO public.attendance_thresholds (id, name, min_percentage, max_percentage, color, badge_style, label, description, "order", is_active, created_at, updated_at) VALUES (%s, %L, %s, %s, %L, %L, %L, %L, %s, %L, %L, %L);',
  id, name, min_percentage, coalesce(max_percentage::text, 'NULL'), color, badge_style, label, description, "order", is_active, created_at, updated_at)
FROM public.attendance_thresholds ORDER BY id;
"""

SEED_HEADER = """\
-- Reference rows copied (read-only SELECT) from live attendancedb.
-- Loaded into every test database after baseline.sql.
"""

SEED_FOOTER = """
SELECT pg_catalog.setval('public.system_settings_id_seq', (SELECT max(id) FROM public.system_settings));
SELECT pg_catalog.setval('public.attendance_thresholds_id_seq', (SELECT max(id) FROM public.attendance_thresholds));
"""


def _tool(pg_bin: str | None, name: str) -> str:
    exe = name + (".exe" if os.name == "nt" else "")
    if pg_bin:
        return str(Path(pg_bin) / exe)
    found = shutil.which(name)
    if found:
        return found
    default = Path("C:/Program Files/PostgreSQL/17/bin") / exe
    if default.exists():
        return str(default)
    raise SystemExit(f"{name} not found; pass --pg-bin")


def _env() -> dict[str, str]:
    srv = server_url()
    env = dict(os.environ)
    env.update(
        PGHOST=srv.host or "localhost",
        PGPORT=str(srv.port or 5432),
        PGUSER=srv.username or "postgres",
        PGPASSWORD=srv.password or "",
        PGOPTIONS="-c default_transaction_read_only=on",
    )
    return env


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", action="store_true", help="also regenerate seed_reference.sql")
    parser.add_argument("--pg-bin", default=None)
    args = parser.parse_args()

    dump = subprocess.run(
        [
            _tool(args.pg_bin, "pg_dump"),
            "--schema-only",
            "--no-owner",
            "--no-privileges",
            "-T",
            "students_backup_*",
            "-d",
            LIVE_DB_NAME,
        ],
        env=_env(),
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).stdout
    BASELINE_SQL.write_text(HEADER + clean_dump_sql(dump), encoding="utf-8", newline="\n")
    print(f"wrote {BASELINE_SQL}")

    if args.seed:
        rows = subprocess.run(
            [_tool(args.pg_bin, "psql"), "-d", LIVE_DB_NAME, "-At", "-v", "ON_ERROR_STOP=1"],
            input=SEED_QUERY,
            env=_env(),
            check=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
        ).stdout
        SEED_SQL.write_text(SEED_HEADER + rows.strip() + "\n" + SEED_FOOTER, encoding="utf-8", newline="\n")
        print(f"wrote {SEED_SQL}")


if __name__ == "__main__":
    main()
